def _find_component_dir(pbip_dir: Path, suffixes: Iterable[str]) -> Optional[Path]:
    for candidate in pbip_dir.iterdir():
        if candidate.is_dir() and any(
            candidate.name.endswith(suffix) for suffix in suffixes
        ):
            return candidate
    return None


def _build_report_layout_from_pbip(report_dir: Path) -> Dict[str, Any]:
    """Collapse a ``.Report/`` PBIP folder into the ``Report/Layout`` JSON.

    The PBIP folder structure is::

        Report/
            definition.pbir
            definition/
                report.json
                pages/<name>/page.json
                pages/<name>/visuals/visual_*.json

    Power BI's monolithic ``.pbit`` format stores the same data as
    a single ``Report/Layout`` JSON. The mapping is:

    * ``report.json.pages`` → ``Layout.pages[*]``
    * Each ``pages/<name>/page.json`` → embedded into the
      corresponding ``Layout.pages[i]`` entry.
    * Each ``visuals/visual_*.json`` → appended to
      ``Layout.pages[i].visualContainers``.
    """
    definition_dir = report_dir / "definition"
    if not definition_dir.is_dir():
        return {"pages": [], "settings": {}}
    report_json_path = definition_dir / "report.json"
    if not report_json_path.is_file():
        return {"pages": [], "settings": {}}
    report_data = json.loads(report_json_path.read_text(encoding="utf-8"))
    # Ingest each page directory and merge its contents into the
    # corresponding entry of ``report_data.pages``.
    pages_dir = definition_dir / "pages"
    pages = report_data.get("pages") or []
    for page_entry in pages:
        page_name = page_entry.get("name")
        if not page_name:
            continue
        page_dir = pages_dir / page_name
        if not page_dir.is_dir():
            continue
        page_json_path = page_dir / "page.json"
        if page_json_path.is_file():
            page_entry.update(json.loads(page_json_path.read_text(encoding="utf-8")))
        visuals_dir = page_dir / "visuals"
        if visuals_dir.is_dir():
            page_entry["visualContainers"] = [
                json.loads(vis.read_text(encoding="utf-8"))
                for vis in sorted(visuals_dir.glob("visual_*.json"))
            ]
    return report_data


def _match_glob(path: str, glob: str) -> bool:
    """Match a forward-slash ``path`` against a simple ``glob`` pattern.

    Rules:

    * ``*`` matches any characters except ``/``.
    * ``**`` matches any characters including ``/``.
    * ``?`` matches a single character that is not ``/``.

    Implemented as a regex translation rather than :mod:`fnmatch`
    because :mod:`fnmatch` doesn't distinguish ``/``-aware ``*``
    from cross-directory ``**``.
    """
    import re

    # Escape regex metacharacters except the glob ones we want to
    # translate (``*`` and ``?``).
    parts = re.split(r"(\*\*|\*|\?)", glob)
    regex = ""
    for part in parts:
        if part == "*":
            # Single-segment wildcard: any chars except ``/``.
            regex = f"{regex}[^/]*"
        elif part == "**":
            # Cross-segment wildcard: any chars including ``/``.
            regex = f"{regex}.*"
        elif part == "?":
            # Single non-separator character.
            regex = f"{regex}[^/]"
        else:
            regex = f"{regex}{re.escape(part)}"
    return re.fullmatch(regex, path) is not None


def _build_logger() -> Any:
    import logging

    return logging.getLogger(__name__)
